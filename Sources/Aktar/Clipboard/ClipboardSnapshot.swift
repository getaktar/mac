import AppKit

/// What was on the clipboard before Aktar copied a link, so Undo can put
/// it back (docs/capture-and-instant-links.md, "Undo").
struct ClipboardSnapshot {
    /// Each item's types and data, in the order the pasteboard had them.
    let items: [[(type: NSPasteboard.PasteboardType, data: Data)]]

    /// Bigger clipboards aren't kept.
    static let maxBytes = 64 * 1024 * 1024

    /// Marks (nspasteboard.org) that password managers and the like put on
    /// what they copy. Such a clipboard is never kept: putting a password
    /// back after its app stopped watching would leave it there for good.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// The clipboard as it is, or nil when it can't be put back later:
    /// too big, or marked private. An empty clipboard is an empty snapshot.
    @MainActor
    static func take(from pasteboard: NSPasteboard = .general) -> ClipboardSnapshot? {
        let pasteboardItems = pasteboard.pasteboardItems ?? []
        var total = 0
        var items: [[(type: NSPasteboard.PasteboardType, data: Data)]] = []
        for item in pasteboardItems {
            if item.types.contains(where: { privateTypes.contains($0.rawValue) }) { return nil }
            var entries: [(type: NSPasteboard.PasteboardType, data: Data)] = []
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                if total > maxBytes { return nil }
                entries.append((type, data))
            }
            if !entries.isEmpty { items.append(entries) }
        }
        return ClipboardSnapshot(items: items)
    }

    @MainActor
    func restore(to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        let restored = items.map { entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for entry in entries { item.setData(entry.data, forType: entry.type) }
            return item
        }
        pasteboard.writeObjects(restored)
    }
}
